'use client'

import { Suspense, useState } from 'react'
import { useSearchParams, useRouter } from 'next/navigation'
import { PixelLayout } from '@/components/layout/PixelLayout'
import { PixelPanel } from '@/components/ui/PixelPanel'
import { PixelButton } from '@/components/ui/PixelButton'
import { config } from '@/lib/config'

function MockPaymentContent() {
  const params = useSearchParams()
  const router = useRouter()

  const order  = params.get('order') ?? ''
  const email  = params.get('email') ?? ''
  const tier   = params.get('tier') ?? ''
  const amount = params.get('amount') ?? ''

  const [loading, setLoading] = useState(false)
  const [error, setError] = useState('')

  const handleConfirm = async () => {
    setError('')
    setLoading(true)
    try {
      const res = await fetch(`${config.api.baseUrl}/api/payments/dev-mock-confirm`, {
        method:  'POST',
        headers: { 'Content-Type': 'application/json' },
        body:    JSON.stringify({ order_id: order }),
      })
      if (!res.ok) {
        const data = await res.json().catch(() => ({}))
        throw new Error(data.detail ?? `Confirm failed: ${res.status}`)
      }
      router.push(`/create?email=${encodeURIComponent(email)}&ref=${order}`)
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Could not confirm mock payment.')
      setLoading(false)
    }
  }

  if (!order || !email) {
    return (
      <PixelPanel padding="lg" className="max-w-md mx-auto text-center space-y-3">
        <p className="font-press text-xs text-pixel-error">
          Missing order/email — this page only works via a link generated by the real payment flow.
        </p>
      </PixelPanel>
    )
  }

  return (
    <PixelPanel padding="lg" className="space-y-5 max-w-md mx-auto">
      <div className="text-center space-y-2">
        <p className="font-press text-[0.4rem] text-pixel-error uppercase tracking-widest">
          ⚠ Dev mode — not a real checkout
        </p>
        <h1 className="font-pixel text-base text-pixel-gold">Mock Payment</h1>
        <p className="font-body text-sm text-pixel-muted">
          MAYAR_API_KEY isn&apos;t configured on the backend, so this stands in for Mayar&apos;s
          hosted checkout page.
        </p>
      </div>

      <div className="font-body text-sm text-pixel-text space-y-1 border-t border-b border-pixel-border py-3">
        <p><span className="text-pixel-muted">Email:</span> {email}</p>
        {tier && <p><span className="text-pixel-muted">Plan:</span> {tier}</p>}
        {amount && (
          <p><span className="text-pixel-muted">Amount:</span> Rp {Number(amount).toLocaleString('id-ID')}</p>
        )}
        <p><span className="text-pixel-muted">Order:</span> {order}</p>
      </div>

      {error && <p role="alert" className="font-press text-[0.38rem] text-pixel-error">{error}</p>}

      <PixelButton variant="primary" disabled={loading} onClick={handleConfirm} className="w-full">
        {loading ? 'Confirming…' : '✓ Simulate Successful Payment'}
      </PixelButton>
    </PixelPanel>
  )
}

export default function DevMockPaymentPage() {
  return (
    <PixelLayout>
      <div className="min-h-[70vh] flex items-center justify-center px-4 py-12">
        <Suspense fallback={null}>
          <MockPaymentContent />
        </Suspense>
      </div>
    </PixelLayout>
  )
}
